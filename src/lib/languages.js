/**
 * Définitions de langues et détection automatique du layout clavier.
 * Chaque langue fournit un nom d'affichage, un label court, un alphabet
 * (pour le mode incohérent), et une liste de mots (pour le mode cohérent).
 */

/**
 * Détection du layout clavier via l'API Keyboard (Chromium, contexte sécurisé).
 * Retourne "qwerty" ou "azerty" en fonction de la position de KeyA.
 * Fallback : "qwerty".
 * @returns {Promise<"qwerty"|"azerty">}
 */
export async function detectKeyboardLayout() {
  if (typeof navigator === "undefined" || !navigator.keyboard) return "qwerty";
  try {
    const map = await navigator.keyboard.getLayoutMap();
    return map.get("KeyA") === "q" ? "azerty" : "qwerty";
  } catch {
    return "qwerty";
  }
}

