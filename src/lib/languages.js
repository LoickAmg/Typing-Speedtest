/**
 * Retourne une langue par son code.
 * @param {string} code
 * @returns {object|undefined}
 */
export function getLanguage(code) {
  return LANGUAGES.find((l) => l.code === code);
}

/**
 * Génère un mot aléatoire dans une langue donnée.
 * @param {string} code - Code de langue (ex: "fr")
 * @param {function} rng - Générateur aléatoire [0,1)
 * @returns {string}
 */
export function getRandomWord(code, rng) {
  const lang = getLanguage(code);
  if (!lang) return "word";
  return lang.words[Math.floor(rng() * lang.words.length)];
}

/**
 * Génère une séquence incohérente (3-8 caractères) dans l'alphabet de la langue.
 * @param {string} code - Code de langue
 * @param {function} rng - Générateur aléatoire [0,1)
 * @returns {string}
 */
export function generateIncoherentWord(code, rng) {
  const lang = getLanguage(code);
  if (!lang) return "xyz";
  const alpha = lang.alphabet;
  const len = 3 + Math.floor(rng() * 6);
  let word = "";
  for (let i = 0; i < len; i++) {
    word += alpha[Math.floor(rng() * alpha.length)];
  }
  return word;
}

